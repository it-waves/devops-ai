const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const BASE = process.env.BASE || 'http://localhost:8081/cloudcart/';
let fails = 0;
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const br = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  const pg = await (await br.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
  const errs = []; pg.on('pageerror', e => errs.push(e.message)); pg.on('console', m => m.type() === 'error' && !/Failed to load resource: the server responded with a status of (400|404)/.test(m.text()) && errs.push(m.text()));
  await pg.goto(BASE); await pg.waitForSelector('.card');
  ok(await pg.locator('.card').count() === 12, 'home lists 12 products');
  ok(await pg.locator('#badge').isHidden(), 'cart badge hidden when empty');
  await pg.fill('#q', 'lamp'); await pg.press('#q', 'Enter'); await pg.waitForFunction(() => document.querySelectorAll('.card').length === 1);
  ok(true, 'search lamp gives 1 result');
  await pg.fill('#q', 'zzzz'); await pg.press('#q', 'Enter'); await pg.waitForSelector('.empty');
  ok(/Nothing matches/.test(await pg.textContent('main')), 'no-result state shown');
  await pg.goto(BASE + '#/'); await pg.waitForSelector('.card');
  await pg.click('[data-cat="Audio"]'); await pg.waitForFunction(() => document.querySelectorAll('.card').length === 3);
  ok(true, 'category filter Audio gives 3');
  await pg.selectOption('#sort', 'price-asc'); await pg.waitForTimeout(500);
  ok((await pg.locator('.card .price').first().textContent()) === '$64.00', 'sort price low to high');
  ok(await pg.locator('.card button[disabled]').count() === 1, 'out-of-stock mic cannot be added');
  await pg.screenshot({ path: '/tmp/shots/e_audio.png' });
  await pg.goto(BASE + '#/'); await pg.waitForSelector('.card');
  await pg.locator('[data-add="9"]').click(); await pg.waitForFunction(() => document.querySelector('#badge').textContent === '1');
  await pg.goto(BASE + '#/product/10'); await pg.waitForSelector('#inc'); await pg.click('#inc'); await pg.click('#inc'); await pg.click('#add');
  await pg.waitForFunction(() => document.querySelector('#badge').textContent === '4');
  ok(true, 'badge counts 4 after adding');
  await pg.goto(BASE + '#/cart'); await pg.waitForSelector('.line');
  await pg.locator('[data-q="9"][data-d="1"]').click(); await pg.waitForFunction(() => /\$56\.00/.test(document.body.innerText));
  ok(true, 'cart quantity + updates the line');
  await pg.screenshot({ path: '/tmp/shots/e_cart.png' });
  await pg.click('text=Checkout'); await pg.waitForSelector('#af');
  ok(pg.url().endsWith('#/signin'), 'checkout asks to sign in');
  await pg.click('#fill'); await pg.click('form#af button.btn');
  await pg.waitForSelector('#co'); ok(true, 'sign in returns to checkout');
  await pg.fill('[name=name]', ''); await pg.click('#place');
  ok(/full name/.test(await pg.textContent('#err')), 'checkout validates empty name');
  await pg.fill('[name=name]', 'Sam Student'); await pg.fill('[name=address]', '1 Main Street'); await pg.fill('[name=city]', 'Austin'); await pg.fill('[name=zip]', '78');
  await pg.click('#place'); ok(/5 digits/.test(await pg.textContent('#err')), 'checkout validates ZIP');
  await pg.screenshot({ path: '/tmp/shots/e_checkout.png' });
  await pg.fill('[name=zip]', '78701'); await pg.click('#place'); await pg.waitForSelector('.done');
  ok(/CC-\d+/.test(await pg.textContent('.done')), 'order confirmation shows number');
  await pg.screenshot({ path: '/tmp/shots/e_done.png' });
  ok(await pg.locator('#badge').isHidden(), 'cart is empty after order');
  await pg.click('text=View my orders'); await pg.waitForSelector('.order');
  ok(await pg.locator('.order').count() >= 1, 'order history lists the order');
  await pg.screenshot({ path: '/tmp/shots/e_orders.png' });
  await pg.click('#account'); await pg.waitForFunction(() => document.querySelector('#account').textContent === 'Sign in');
  ok(true, 'sign out works');
  await pg.goto(BASE + '#/signin'); await pg.click('[data-m=register]');
  await pg.fill('[name=name]', 'Ada Lovelace'); await pg.fill('[name=email]', 'ada' + Date.now() + '@example.com'); await pg.fill('[name=password]', 'short');
  await pg.click('form#af button.btn'); await pg.waitForFunction(() => /8 characters/.test(document.querySelector('#err').textContent)); ok(true, 'register rejects short password');
  await pg.fill('[name=password]', 'longenough1'); await pg.click('form#af button.btn'); await pg.waitForFunction(() => /Ada/.test(document.querySelector('#account').textContent));
  ok(true, 'register creates account and signs in');
  await pg.goto(BASE + '#/signin'); await pg.click('#account').catch(() => {});
  await pg.goto(BASE + '#/product/999'); await pg.waitForSelector('.empty'); ok(/not found/i.test(await pg.textContent('main')), 'unknown product shows not-found page');
  await pg.goto(BASE + 'admin.html'); await pg.waitForFunction(() => /UP/.test(document.querySelector('#stt').textContent));
  ok(true, 'admin page shows UP');
  ok(errs.length === 0, 'no console or page errors ' + JSON.stringify(errs));
  await br.close(); console.log(fails ? fails + ' FAILED' : 'ALL PASSED'); process.exit(fails ? 1 : 0);
})().catch(e => { console.log('ERROR', e.message); process.exit(2); });
